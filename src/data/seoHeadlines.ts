// Helper to get active hourly headline based on current hour
export function getHourlyHeadline(date: Date = new Date()): SeoHeadlineItem {
  // Use UTC or Indian Standard Time timestamp in hours to guarantee smooth hourly cycle
  const currentHourIndex = Math.floor(date.getTime() / (1000 * 60 * 60)) % SEO_HEADLINES.length;
  return SEO_HEADLINES[currentHourIndex] || SEO_HEADLINES[0];
}
